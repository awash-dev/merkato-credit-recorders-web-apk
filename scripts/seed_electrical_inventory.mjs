async function seed() {
  console.log('Seeding electrical store inventory...');

  for (const store of STORES) {
    console.log(`\n--- Seeding for ${store.name} (ID: ${store.id}) ---`);

    for (const item of ELECTRICAL_CATALOG) {
      const productId = randomUUID();
      const qty = Math.round(item.baseQty * store.multiplier);
      const cartons = Number((qty / item.pcsPerCarton).toFixed(2));
      const sku = `${item.skuBase}-${store.suffix}`;
      const totalValue = Number((qty * item.costPrice).toFixed(2));

      // 1. Insert into store_inventory
      await sql`
        INSERT INTO store_inventory (
          id,
          store_id,
          product_name,
          sku,
          category,
          base_unit,
          unit,
          pcs_per_carton,
          quantity_per_carton,
          quantity_cartons,
          current_quantity,
          total_quantity,
          cost_price,
          unit_price,
          price_per_piece,
          storekeeper_price,
          total_value,
          minimum_stock,
          supplier_name,
          description,
          last_transaction_date,
          is_active,
          is_deleted,
          created_at,
          updated_at
        ) VALUES (
          ${productId}::uuid,
          ${store.id},
          ${item.name},
          ${sku},
          ${item.category},
          ${item.unit},
          ${item.unit},
          ${item.pcsPerCarton},
          ${item.pcsPerCarton},
          ${cartons},
          ${qty},
          ${qty},
          ${item.costPrice},
          ${item.unitPrice},
          ${item.unitPrice},
          ${item.storekeeperPrice},
          ${totalValue},
          ${item.minStock},
          ${item.supplier},
          ${item.description},
          '2026-11-09',
          TRUE,
          FALSE,
          CURRENT_TIMESTAMP,
          CURRENT_TIMESTAMP
        )
      `;

      // 2. Insert into stock_movements (Initial Stock IN)
      const movementId = randomUUID();
      await sql`
        INSERT INTO stock_movements (
          id,
          product_id,
          store_id,
          movement_type,
          quantity,
          base_quantity,
          cartons,
          loose_pieces,
          total_pieces,
          previous_stock,
          new_stock,
          unit_price,
          total_price,
          storekeeper_price,
          conversion_factor,
          transaction_unit,
          transaction_date,
          source_type,
          note,
          created_at
        ) VALUES (
          ${movementId}::uuid,
          ${productId}::uuid,
          ${store.id},
          'IN',
          ${qty},
          ${qty},
          ${cartons},
          ${qty % item.pcsPerCarton},
          ${qty},
          0,
          ${qty},
          ${item.costPrice},
          ${totalValue},
          ${item.storekeeperPrice},
          ${item.pcsPerCarton},
          ${item.unit},
          '2026-11-09',
          'INITIAL_STOCK',
          'Initial stock intake for store',
          CURRENT_TIMESTAMP
        )
      `;

      console.log(`✓ [${store.name}] ${item.name} seeded: ${qty} pcs (${cartons} ctns) @ ETB ${item.unitPrice} (Storekeeper: ETB ${item.storekeeperPrice})`);
    }
  }

  console.log('\nAll electrical inventory seeded successfully for both stores!');
}

seed().catch(err => {
  console.error('Seeding error:', err);
  process.exit(1);
});

